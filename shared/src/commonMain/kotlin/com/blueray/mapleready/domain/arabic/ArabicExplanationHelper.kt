package com.blueray.mapleready.domain.arabic

import com.blueray.mapleready.domain.practice.model.PracticeQuestion
import com.blueray.mapleready.domain.study.model.StudyTopicId

object ArabicExplanationHelper {

    fun getStudySectionExplanation(
        topicId: StudyTopicId,
        sectionIndex: Int,
        sectionTitle: String,
        sectionContent: String
    ): String {
        return when (topicId) {
            StudyTopicId.HISTORY -> getHistoryExplanation(sectionIndex, sectionTitle)
            StudyTopicId.RIGHTS_AND_RESPONSIBILITIES -> getRightsExplanation(sectionIndex, sectionTitle)
            StudyTopicId.GOVERNMENT -> getGovernmentExplanation(sectionIndex, sectionTitle)
            StudyTopicId.ELECTIONS -> getElectionsExplanation(sectionIndex, sectionTitle)
            StudyTopicId.GEOGRAPHY -> getGeographyExplanation(sectionIndex, sectionTitle)
        }
    }

    fun getQuestionExplanation(question: PracticeQuestion): String {
        val correctAnswer = question.answers.firstOrNull { it.isCorrect }?.text ?: ""

        return when (question.topicId) {
            StudyTopicId.HISTORY ->
                "السؤال يخص التاريخ الكندي:\n«${question.text}»\n\n" +
                "الإجابة الصحيحة هي:\n«$correctAnswer»\n\n" +
                "توضيح وملاحظة هامة:\nيتناول هذا السؤال حدثاً تاريخياً مفصلياً في تأسيس كندا وتطورها السيادي. حِفظ الشخصيات والتواريخ الرئيسية المذكورة في كتاب Discover Canada يساعدك بشكل كبير على اجتياز الاختبار بنجاح."

            StudyTopicId.RIGHTS_AND_RESPONSIBILITIES ->
                "السؤال يخص الحقوق والمسؤوليات:\n«${question.text}»\n\n" +
                "الإجابة الصحيحة هي:\n«$correctAnswer»\n\n" +
                "توضيح وملاحظة هامة:\nيضمن ميثاق الحقوق والحريات الكندي (Canadian Charter of Rights and Freedoms) الحرية الدينية، حرية التعبير، حرية التنقل، والمساواة الكاملة أمام القانون بدون أي تمييز."

            StudyTopicId.GOVERNMENT ->
                "السؤال يخص نظام الحكم والمؤسسات:\n«${question.text}»\n\n" +
                "الإجابة الصحيحة هي:\n«$correctAnswer»\n\n" +
                "توضيح وملاحظة هامة:\nكندا دولة ذات نظام ديمقراطي برلماني وملكية دستورية. يتكون النظام الفيدرالي من السلطة التنفيذية (رئيس الوزراء والوزراء)، التشريعية (مجلس العموم والشيوخ)، والقضائية (المحاكم)."

            StudyTopicId.ELECTIONS ->
                "السؤال يخص الانتخابات وحق الاقتراع:\n«${question.text}»\n\n" +
                "الإجابة الصحيحة هي:\n«$correctAnswer»\n\n" +
                "توضيح وملاحظة هامة:\nتُجرى الانتخابات الفيدرالية كل 4 سنوات باقتراع سري. يحق لكل مواطن كندي بلغ 18 عاماً ومسجل في سجل الناخبين ممارسة حقه الانتخابي بكل حرية."

            StudyTopicId.GEOGRAPHY ->
                "السؤال يخص جغرافية كندا ومناطقها:\n«${question.text}»\n\n" +
                "الإجابة الصحيحة هي:\n«$correctAnswer»\n\n" +
                "توضيح وملاحظة هامة:\nتتكون كندا من 10 مقاطعات و3 أقاليم موزعة على 5 مناطق جغرافية: الأطلسي، كندا الوسطى، البراري، الساحل الغربي، والشمال."
        }
    }

    private fun getHistoryExplanation(index: Int, title: String): String {
        return "عنوان الفكرة: $title\n\n" +
                "الشرح والتوضيح بالعربية:\n" +
                when (index % 10) {
                    0 -> "يبدأ تاريخ كندا بالشعوب الأصلية التي عاشت على هذه الأرض لآلاف السنين: سكان الأمم الأولى (First Nations)، الإينويت (Inuit)، والميتيس (Métis)."
                    1 -> "استكشف الفرنسي جاك كارتيه كندا في القرن 16. وفي عام 1608 أسس صامويل دي شامبلان مدينة كيبيك كأول مستوطنة أوروبية دائمة."
                    2 -> "اعتمد اقتصاد فرنسا الجديدة على تجارة الفراء من خلال تجار الفراء والرحالة بالتعاون الوثيق مع السكان الأصليين."
                    3 -> "منح قانون كيبيك لعام 1774 حرية الممارسة الدينية للكاثوليك وأعاد القانون المدني الفرنسي، مما أرسى قيم التنوع والتسامح الكندي."
                    4 -> "في حرب 1812، اتحدت القوات البريطانية مع القوات المحلية والسكان الأصليين لصد الغزو الأمريكي وحماية استقلال كندا."
                    5 -> "في 1 يوليو 1867، أُنشئ الاتحاد الكندي (Confederation) بموجب قانون BNA Act، وأصبح سير جون ماكدونالد أول رئيس وزراء لكندا."
                    6 -> "ربطت السكة الحديدية للكاناديان باسيفيك (CPR) عام 1885 كولومبيا البريطانية بالشرق وفتحت باب الاستيطان في أراضي البراري."
                    7 -> "شارك أكثر من 600 ألف كندي في الحرب العالمية الأولى. وكانت معركة فيمي ريدج (Vimy Ridge) عام 1917 نقطة تحول نضجت فيها الهوية الوطنية."
                    8 -> "في الحرب العالمية الثانية، شارك أكثر من مليون كندي. وفي يوم الإنـزال (D-Day) عام 1944 سيطرت القوات الكندية على شاطئ جونو (Juno Beach)."
                    else -> "في عام 1982، قام رئيس الوزراء بيير ترودو باستعادة الدستور الكندي وإضافة ميثاق الحقوق والحريات لضمان الحقوق الديمقراطية والإنسانية."
                }
    }

